"""An SSF receiver, framework independent and asyncio based: SET verification, de-duplication,
push and poll delivery, stream management, typed CAEP, RISC and SCIM handlers, token revocation,
session termination and metrics. The port of ``easyssf-receiver`` of the Java library.

The modules follow the Go package: ``errors`` (the exception classes and the ``Clock``), ``event``
(``EventContext`` and the handlers), ``dedup``, ``metrics``, ``config`` (``ReceiverConfig``),
``jwks``, ``verifier``, ``processor``, ``push``, ``authorizer``, ``transmitter``, ``stream``,
``poll``, ``receiver`` (``Receiver``, which assembles everything from a ``ReceiverConfig``), the
typed handlers ``caep``, ``risc`` and ``scim``, ``revocation`` and ``session``; ``asgi`` and
``wsgi`` mount the push endpoint on any web framework.
"""

